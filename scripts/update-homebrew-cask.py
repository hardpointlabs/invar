#!/usr/bin/env python3
"""Update the invar Cask in the Homebrew tap for a new release.

Usage: update-homebrew-cask.py CASK_FILE VERSION ARCHIVE=SHA256 [ARCHIVE=SHA256 ...]

ARCHIVE is the release asset's basename without ".tar.gz" (e.g.
invar_Darwin_arm64). Rewrites the Cask's `version` and the `sha256` that sits
directly above each matching `url`. Every ARCHIVE given must be found, and the
Cask must reference no archive that wasn't given, so a platform can't be left
with a stale checksum. Idempotent: rerunning with the same inputs is a no-op.
"""
import re
import sys

cask_path, version, *pairs = sys.argv[1:]
if not re.fullmatch(r"\d+\.\d+\.\d+", version) or not pairs:
    sys.exit(__doc__)
shas = dict(p.split("=", 1) for p in pairs)
for archive, sha in shas.items():
    if not re.fullmatch(r"[0-9a-f]{64}", sha):
        sys.exit(f"bad sha256 for {archive}: {sha!r}")

text = open(cask_path).read()

text, n = re.subn(r'(?m)^(\s*version\s+)"[^"]*"', rf'\g<1>"{version}"', text, count=1)
if n != 1:
    sys.exit("no version line found in cask")

seen = set()


def swap(m):
    archive = m.group("archive")
    if archive not in shas:
        sys.exit(f"cask references {archive}, which has no checksum supplied")
    seen.add(archive)
    return f'{m.group("pre")}"{shas[archive]}"{m.group("mid")}'


text = re.sub(
    r'(?P<pre>sha256\s+)"[0-9a-f]{64}"(?P<mid>\s*\n\s*url\s+"[^"\n]*/(?P<archive>[^"/\n]+?)\.tar\.gz")',
    swap,
    text,
)
if seen != set(shas):
    sys.exit(f"archives not found in cask: {sorted(set(shas) - seen)}")

# The cask is no longer generated by GoReleaser.
text = text.replace(
    "# This file was generated by GoReleaser. DO NOT EDIT.",
    "# Updated by the hardpointlabs/invar release workflow.",
    1,
)
open(cask_path, "w").write(text)
